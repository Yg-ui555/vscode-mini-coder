/**
 * 14-hard-refactor-extract 的标准答案
 *
 * ⭐ 这份文件的作用是【证明这道题可解】：
 *   verifySolvable.ts 会把 initial/ 复制到沙箱、执行本文件、再跑全部 case，
 *   要求一个 case 都不挂。
 *
 * 标准答案的写法：把大函数 processOrder 拆成五个职责单一的小函数，
 * 全部导出（这样才测得到），并且给 calcShipping 加上「折后金额满 200 免运费」。
 *
 * ⚠️ 本题的核心约束是【输出一个字都不能变】：
 *   check.js 里硬编码了 7 组订单的精确期望输出，格式、顺序、toFixed(2) 的精度、
 *   警告行的位置全都要原样。所以拆分时：
 *   · 计算顺序不动（浮点精度依赖它）
 *   · 促销判断从 processOrder 里挪进 calcDiscount，别在原地留一份
 *   · 折扣仍然不超过小计（小计不能变成负数）
 *
 * ⚠️ 为什么 calcDiscount 里的变量叫 rule 而不是 promo：
 *   check.js 有一条提示性断言，会检查 processOrder 之后的内容里
 *   还能不能搜到 `if (promo.type ===`。把促销判断挪进独立函数、
 *   并且换个变量名，这条断言在任何文件顺序下都不会误伤。
 */

const fs = require('fs');
const path = require('path');

module.exports = {
  taskId: '14-hard-refactor-extract',

  apply(dir) {
    fs.writeFileSync(
      path.join(dir, 'processor.js'),
      [
        '/**',
        ' * 订单处理 —— 校验、计价、促销、运费、格式化各归各家',
        ' *',
        ' * 拆分前 processOrder 是一个大函数，混杂了五件事；',
        ' * 现在每件事一个函数，计算顺序一个字没动，输出逐字不变。',
        ' */',
        '',
        'const PROMOTIONS = {',
        "  SAVE10: { type: 'percent', value: 0.1 },",
        "  SAVE50: { type: 'fixed', value: 50 },",
        '};',
        '',
        'const SHIPPING_RULES = {',
        '  standard: 10,',
        '  express: 25,',
        '};',
        '',
        '/** 免邮门槛：按【折后金额】算，不是按小计 */',
        'const FREE_SHIPPING_THRESHOLD = 200;',
        '',
        '/**',
        ' * 校验订单',
        ' * @param {Object} order',
        ' * @returns {boolean}',
        ' */',
        'function validateOrder(order) {',
        '  if (!order || !order.items) return false;',
        '  return true;',
        '}',
        '',
        '/**',
        ' * 算小计；顺带把无效价格的警告收集起来（顺序与原来一致）',
        ' * @param {Array} items',
        ' * @param {string[]} errors',
        ' * @returns {number}',
        ' */',
        'function calcSubtotal(items, errors) {',
        '  let subtotal = 0;',
        '  for (const item of items) {',
        '    if (!item.price || item.price < 0) {',
        '      errors.push(`无效价格: ${item.name}`);',
        '      continue;',
        '    }',
        '    let price = item.price;',
        '    if (item.quantity > 1) {',
        '      price = item.price * item.quantity;',
        '    }',
        '    subtotal += price;',
        '  }',
        '  return subtotal;',
        '}',
        '',
        '/**',
        ' * 应用促销，算出折扣金额',
        ' * @param {number} subtotal',
        ' * @param {string} promoCode',
        ' * @returns {number}',
        ' */',
        'function calcDiscount(subtotal, promoCode) {',
        '  const rule = PROMOTIONS[promoCode];',
        '  if (!rule) return 0;',
        '  if (rule.type === \'percent\') {',
        '    return subtotal * rule.value;',
        '  }',
        '  if (rule.type === \'fixed\') {',
        '    // 折扣不能超过小计，否则小计会变成负数',
        '    return Math.min(rule.value, subtotal);',
        '  }',
        '  return 0;',
        '}',
        '',
        '/**',
        ' * 算运费：折后金额满 200 免运费，否则按配送方式收费',
        ' * （未知配送方式回退到 standard）',
        ' * @param {number} amountAfterDiscount 折后金额',
        ' * @param {string} method 配送方式',
        ' * @returns {number}',
        ' */',
        'function calcShipping(amountAfterDiscount, method) {',
        '  if (amountAfterDiscount >= FREE_SHIPPING_THRESHOLD) {',
        '    return 0;',
        '  }',
        '  const fee = SHIPPING_RULES[method];',
        '  return fee === undefined ? SHIPPING_RULES.standard : fee;',
        '}',
        '',
        '/**',
        ' * 格式化输出：表头 + 每一行商品 + 小计 / 折扣 / 运费 / 总计 + 警告',
        ' * @param {Object} order',
        ' * @param {number} subtotal',
        ' * @param {number} discount',
        ' * @param {number} shipping',
        ' * @param {number} total',
        ' * @param {string[]} errors',
        ' * @returns {string}',
        ' */',
        'function formatOrder(order, subtotal, discount, shipping, total, errors) {',
        '  const lines = [];',
        "  lines.push('=== 订单 ===');",
        '  for (const item of order.items) {',
        '    lines.push(`  ${item.name} x${item.quantity || 1}`);',
        '  }',
        '  lines.push(`小计: ${subtotal.toFixed(2)}`);',
        '  if (discount > 0) {',
        '    lines.push(`折扣: -${discount.toFixed(2)}`);',
        '  }',
        '  lines.push(`运费: ${shipping.toFixed(2)}`);',
        '  lines.push(`总计: ${total.toFixed(2)}`);',
        '  if (errors.length > 0) {',
        "    lines.push('警告:');",
        '    for (const e of errors) {',
        '      lines.push(`  ${e}`);',
        '    }',
        '  }',
        '',
        "  return lines.join('\\n');",
        '}',
        '',
        '/**',
        ' * 订单主流程：校验 -> 小计 -> 促销 -> 运费 -> 格式化',
        ' * @param {Object} order',
        ' * @returns {string}',
        ' */',
        'function processOrder(order) {',
        '  if (!validateOrder(order)) {',
        "    return 'ERROR: 订单格式错误';",
        '  }',
        '',
        '  const errors = [];',
        '  const subtotal = calcSubtotal(order.items, errors);',
        '  const discount = calcDiscount(subtotal, order.promo);',
        '  const afterDiscount = subtotal - discount;',
        '  // 门槛看的是折后金额：200 - 20 = 180 < 200，所以那一单仍然要收运费',
        "  const shipping = calcShipping(afterDiscount, order.shippingMethod || 'standard');",
        '  const total = afterDiscount + shipping;',
        '',
        '  return formatOrder(order, subtotal, discount, shipping, total, errors);',
        '}',
        '',
        'module.exports = {',
        '  processOrder,',
        '  validateOrder,',
        '  calcSubtotal,',
        '  calcDiscount,',
        '  calcShipping,',
        '  formatOrder,',
        '};',
        '',
      ].join('\n'),
      'utf-8'
    );
  },
};
