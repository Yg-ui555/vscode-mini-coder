/**
 * 12-hard-edge-parser 的标准答案
 *
 * ⭐ 这份文件的作用是【证明这道题可解】：
 *   verifySolvable.ts 会把 initial/ 复制到沙箱、执行本文件、再跑全部 case，
 *   要求一个 case 都不挂。
 *
 * 标准答案的写法：只重写 parseQuery，另外加两个【不导出】的私有小工具
 *   · decodeComponent：先 '+' -> 空格，再 decodeURIComponent，畸形转义保留原样
 *   · assign：同一个 key 第二次出现就升级成数组（保持出现顺序）
 * stringifyQuery / countPairs / splitPairs / parseQuerySafely 一个字都不动。
 *
 * ⚠️ 这道题最容易漏的边界：
 *   · 解码顺序：先 '+' 换空格再解码，反了会把 %2B 错当成空格
 *   · 畸形转义（a=%E4）不能抛异常，要保留原始字符串
 *   · 重复 key -> 数组；只出现一次的 key 仍然是字符串（不能一律塞数组）
 *   · 裸 flag -> null；同一个 key 既有值又有裸 flag 时并进数组（顺序在后面）
 *   · 空片段（连续的 &、开头的 &）跳过，不能产生 { '': null }
 *   · 空 key（=5）照常处理；单独一个 '=' 是空 key 空 value
 */

const fs = require('fs');
const path = require('path');

module.exports = {
  taskId: '12-hard-edge-parser',

  apply(dir) {
    fs.writeFileSync(
      path.join(dir, 'parser.js'),
      [
        '/**',
        ' * 极简 query string 解析 / 序列化',
        ' *',
        ' * parseQuery 现在支持：URL 解码、重复 key 收集成数组、裸 flag 记成 null。',
        ' */',
        '',
        "const PAIR_SEP = '&';",
        "const KEY_VALUE_SEP = '=';",
        '',
        '/**',
        ' * URL 解码一个片段',
        ' *',
        ' * ⚠️ 顺序很重要：先把 + 全换成空格，再 decodeURIComponent。',
        ' *    顺序反了会把 %2B（本意是字面量 +）错当成空格。',
        ' * @param {string} raw',
        ' * @returns {string}',
        ' */',
        'function decodeComponent(raw) {',
        '  const text = String(raw);',
        "  const plusDecoded = text.replace(/\\+/g, ' ');",
        '  try {',
        '    return decodeURIComponent(plusDecoded);',
        '  } catch (e) {',
        '    // 畸形转义（如 a=%E4）会让 decodeURIComponent 抛 URIError，',
        '    // 这时候保留原始字符串 —— 既不能抛异常，也不能返回 undefined',
        '    return text;',
        '  }',
        '}',
        '',
        '/**',
        ' * 往结果里塞一个值：同一个 key 第二次出现就升级成数组',
        ' * @param {Object} result',
        ' * @param {string} key',
        ' * @param {string|null} value',
        ' */',
        'function assign(result, key, value) {',
        '  if (!Object.prototype.hasOwnProperty.call(result, key)) {',
        '    result[key] = value;',
        '    return;',
        '  }',
        '  const prev = result[key];',
        '  if (Array.isArray(prev)) {',
        '    prev.push(value);',
        '  } else {',
        '    result[key] = [prev, value];',
        '  }',
        '}',
        '',
        '/**',
        ' * 解析 a=1&b=2 这种字符串',
        ' * @param {string} str',
        ' * @returns {Object}',
        ' */',
        'function parseQuery(str) {',
        '  const result = {};',
        '  if (!str) return result;',
        '  for (const part of String(str).split(PAIR_SEP)) {',
        '    // 空片段（开头的 &、结尾的 &、连续的 &&）直接跳过，',
        '    // 否则会凭空多出 { \'\': null }',
        "    if (part === '') continue;",
        '    const i = part.indexOf(KEY_VALUE_SEP);',
        '    if (i < 0) {',
        '      // 裸 flag：没有 = 的非空片段，值记成 null',
        '      assign(result, decodeComponent(part), null);',
        '      continue;',
        '    }',
        '    assign(',
        '      result,',
        '      decodeComponent(part.slice(0, i)),',
        '      decodeComponent(part.slice(i + 1))',
        '    );',
        '  }',
        '  return result;',
        '}',
        '',
        '/**',
        ' * 把对象序列化回 a=1&b=2 这种字符串（值会做 URL 编码）',
        ' * 数组值会展开成重复的 key。',
        ' */',
        'function stringifyQuery(obj) {',
        "  if (!obj || typeof obj !== 'object') return '';",
        '  const parts = [];',
        '  for (const key of Object.keys(obj)) {',
        '    const v = obj[key];',
        '    if (v === null || v === undefined) continue;',
        '    if (Array.isArray(v)) {',
        '      for (const item of v) {',
        '        parts.push(`${encodeURIComponent(key)}${KEY_VALUE_SEP}${encodeURIComponent(String(item))}`);',
        '      }',
        '    } else {',
        '      parts.push(`${encodeURIComponent(key)}${KEY_VALUE_SEP}${encodeURIComponent(String(v))}`);',
        '    }',
        '  }',
        "  return parts.join(PAIR_SEP);",
        '}',
        '',
        '/**',
        ' * 数一数里面有多少个合法的 key=value 片段（裸 flag 和空片段都不算）',
        ' */',
        'function countPairs(str) {',
        "  if (!str || typeof str !== 'string') return 0;",
        '  let n = 0;',
        '  for (const part of str.split(PAIR_SEP)) {',
        "    if (part === '') continue;",
        '    if (part.indexOf(KEY_VALUE_SEP) < 0) continue;',
        '    n += 1;',
        '  }',
        '  return n;',
        '}',
        '',
        '/**',
        ' * 按 & 切成非空片段（不做任何解码）',
        ' */',
        'function splitPairs(str) {',
        "  if (!str || typeof str !== 'string') return [];",
        '  return String(str)',
        '    .split(PAIR_SEP)',
        "    .filter((p) => p !== '');",
        '}',
        '',
        '/**',
        ' * parseQuery 的安全包装，抛异常就返回空对象',
        ' */',
        'function parseQuerySafely(str) {',
        '  try {',
        '    const r = parseQuery(str);',
        "    return r && typeof r === 'object' ? r : {};",
        '  } catch (e) {',
        '    return {};',
        '  }',
        '}',
        '',
        'module.exports = { parseQuery, stringifyQuery, countPairs, splitPairs, parseQuerySafely };',
        '',
      ].join('\n'),
      'utf-8'
    );
  },
};
