/**
 * 全局硬限制 —— 单一真相源
 *
 * ─────────────────────────────────────────────────────────────
 * 为什么要有这个文件（2026-10-22 新增）
 * ─────────────────────────────────────────────────────────────
 *
 *   修复前，max_iterations 这个数字在三处各写各的：
 *     · loop.ts 的默认参数        → 30
 *     · panel.ts 实际传值         → 20
 *     · context.ts 告诉 LLM 的文案 → 写死"max_iterations=30"
 *
 *   也就是说：**LLM 被告知预算 30，实际只有 20。**
 *
 *   后果不是崩，是判断力下降：
 *     模型按 30 轮来做规划，规划到第 25 轮时发现被硬截断，
 *     留下一堆做了一半的事；而它以为自己还有富余，
 *     前期就不会主动收尾。这跟"它不知道自己能做几步"是同一件事。
 *
 *   评测跑出来的数据也印证了这一点：
 *     多道题轮数顶格（20 轮用满），说明它是被动撞上限，
 *     不是主动判断"差不多该收了"。
 *
 * ─────────────────────────────────────────────────────────────
 * 现在的规则
 * ─────────────────────────────────────────────────────────────
 *
 *   这个常量被三处引用，任何一处改动都不会再走偏：
 *     · loop.ts        默认参数
 *     · panel.ts       真实运行时传入值
 *     · eval/cli.ts    评测时的 maxIterations
 *     · context.ts     写进 system prompt 告诉 LLM 的那个数字
 *
 *   ⭐ 最后一条尤其重要：告诉模型的数字必须由常量生成，
 *     手写就会再次漂移。这是本文件存在的主要理由。
 */

/**
 * 单次任务的最大工具调用轮数
 *
 * 取 30 的依据：
 *   · 够复杂的多文件重构任务能跑完（评测里 14 号题用了 13 轮完成）
 *   · 超了会强制收尾（loop.ts 的 _finalizeWithoutTools），
 *     所以卡在 30 不会造成"什么都没交代"，最坏是拿到一份进度总结
 *   · 30 轮 × 每轮约 15k token ≈ 450k token，是可接受的单次上限
 */
export const MAX_ITERATIONS = 30;

/**
 * 达到上限时的强制收尾轮数
 *
 * 触顶后会再发一次【不带工具】的请求，让 LLM 把已完成的工作
 * 总结给用户（见 loop.ts 的 _finalizeWithoutTools）。
 * 这一轮不计入 MAX_ITERATIONS —— 它是"交代后事"，不是"继续干活"。
 */
export const FINALIZE_CALLS = 1;

/** 给 LLM 看的限制说明（单一真相源，避免手写漂移） */
export function describeLimits(): string {
  return [
    `- 最多连续调用工具 ${MAX_ITERATIONS} 轮（这是硬上限，不是建议值）`,
    '- 接近上限时请主动收尾：把已完成的部分讲清楚，不要留一堆做了一半的事',
    '- 单次工具输出 > 30000 字符会被截断（保留头尾，报错在尾部）；' +
      '输出过大时会自动存成文件，对话里只留头尾预览 + 文件路径，需要细节用 read_file 带 offset/limit 读取',
    '- shell 命令默认超时 30 秒',
    '- 改错了可以用 restore_file 或让用户执行 /undo 退回',
    '- 写文件前会自动存 checkpoint，可随时还原',
  ].join('\n');
}